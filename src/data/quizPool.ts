/**
 * สลับลำดับสมาชิกใน Array ด้วยอัลกอริทึม Fisher-Yates Shuffle
 */
function shuffleArray<T>(items: T[]): T[] {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

/**
 * สุ่มสลับตัวเลือก (Options A/B/C) ของคำถาม 1 ข้อ พร้อมอัปเดตตำแหน่ง answer ให้ตรงกับตัวเลือกที่ถูกย้าย
 */
function shuffleQuizOptions(item: QuizItem): QuizItem {
  const indexed = item.options.map((text, idx) => ({
    text,
    isCorrect: idx === item.answer
  }));
  const shuffled = shuffleArray(indexed);
  return {
    q: item.q,
    options: shuffled.map(o => o.text),
    answer: shuffled.findIndex(o => o.isCorrect),
    explain: item.explain
  };
}

/**
 * สร้างชุดข้อสอบ 10 ข้อสำหรับบทเรียน:
 * - รอบแรก (attempt === 0): ใช้ชุดที่ 1 หรือชุดที่สลับลำดับข้อและตัวเลือก
 * - เมื่อกดรีข้อสอบใหม่ (attempt > 0): สลับไปดึงข้อสอบอีกชุด (Set B <-> Set A) และสุ่มสลับลำดับข้อ + สลับตัวเลือกทุกครั้ง
 */
export function buildExamQuestions(
  lesson: Lesson,
  attempt: number,
  previousQuestions: string[] = []
): { questions: QuizItem[]; setLabel: string } {
  const setA = lesson.quiz || [];
  const setB = EXTRA_LESSON_QUIZZES[lesson.id] || [];
  const fullPool = [...setA, ...setB];

  if (attempt === 0) {
    // รอบเริ่มต้น: ใช้ข้อสอบชุดที่ 1 (10 ข้อ) พร้อมสลับตัวเลือก
    const initialSet = setA.slice(0, 10).map(shuffleQuizOptions);
    return {
      questions: initialSet,
      setLabel: 'ชุดที่ 1 (มาตรฐาน)'
    };
  }

  // เมื่อกดรีข้อสอบใหม่:
  // 1. หากเป็นรอบเลขคี่และมี Set B ครบ 10 ข้อ ให้ดึง Set B มาสุ่มลำดับข้อ + สลับตัวเลือก
  // 2. หรือคัดกรองข้อที่ยังไม่เจอในรอบก่อนหน้าเป็นอันดับแรก แล้วสุ่มลำดับข้อทั้งหมด
  const unseen = fullPool.filter(item => !previousQuestions.includes(item.q));
  const seen = fullPool.filter(item => previousQuestions.includes(item.q));

  const pickedRaw = [
    ...shuffleArray(unseen),
    ...shuffleArray(seen)
  ].slice(0, 10);

  const shuffledQuestions = shuffleArray(pickedRaw).map(shuffleQuizOptions);
  const isMostlySetB = pickedRaw.filter(q => setB.some(b => b.q === q.q)).length >= 5;

  return {
    questions: shuffledQuestions,
    setLabel: isMostlySetB ? `ชุดที่ 2 (สุ่มสลับข้อ #${attempt + 1})` : `ชุดผสม (สุ่มสลับข้อ #${attempt + 1})`
  };
}

